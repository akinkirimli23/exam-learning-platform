export function numbersInChoice(text: string): number[] {
  if (text === 'Değişmez.' || text === 'Eşittir.') return [1];
  if (text === 'İki katına çıkar.') return [2];
  if (text === 'Hacminin yarısı batar.') return [0.5];
  return [...text.matchAll(/\d+(?:[.,]\d+)?(?:\/\d+(?:[.,]\d+)?)?/g)].map(match => {
    const [numerator, denominator] = match[0].replaceAll(',', '.').split('/').map(Number);
    return denominator === undefined ? numerator : numerator / denominator;
  });
}
